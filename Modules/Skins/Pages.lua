-- Tempus UI: settings page for the skins module.
local _, T = ...
local UI = T.UI
local W = UI.W

T:RegisterPage("skins", { key = "skins", label = "Skins", order = 1, build = function(p)
    local cfg = function() return T.db.skins end
    p:Section("Look")
    p:Check(cfg, "stockSkin", "Stock skin (keep Tempus features)", "Leaves Blizzard's windows, tooltips, chat and quest tracker in their stock look, and Bagnon/DBM alone, while quest log search keeps working. Overrides the options below. Applies after a reload.")
    p:Section("Blizzard", "Re-themes the game's windows in the Tempus look. Most changes apply after a reload.")
    p:Check(cfg, "windows", "Windows", "Character sheet, spellbook, talents, merchant, mail, bank, loot, menus, friends and more.")
    p:Check(cfg, "parchment", "Parchment reading panels", "Quest dialogs, quest details, gossip, books and mail keep their parchment inside a Tempus frame. Off makes them fully dark with brightened text. Applies after a reload.")
    p:Check(cfg, "tooltips", "Tooltips", "Tempus panels with class, reaction and item-quality borders.")
    p:Check(cfg, "tooltipHealth", "Tooltip health bar")
    p:Check(cfg, "tooltipCursor", "Tooltips follow the cursor")
    p:Check(cfg, "chat", "Chat frames", "Panels behind chat, flat tabs and edit box. Works alongside Prat.")
    p:Slider(cfg, "chatAlpha", "Chat panel opacity", 0, 1, 0.05, UI.pct)
    p:Check(cfg, "chatUnified", "One panel for chat and edit box", "The edit box joins the bottom of the chat panel instead of floating under it. Applies after a reload.")
    p:Check(cfg, "chatTabs", "Modern tabs", "The active tab is bright with an accent underline, other tabs are dimmed, tabs light up on hover, and tabs with unread lines show a count. Whispers pulse in pink. Applies after a reload.")
    p:Check(cfg, "chatFont", "Tempus font in chat", "Uses your Tempus font with a little more space between lines. The size is still set in the chat window's own menu. Applies after a reload.")
    p:Check(cfg, "chatNewButton", "\"Back to newest\" button", "Replaces the scroll arrows with a small button that appears when you scroll up. The mouse wheel still scrolls. Applies after a reload.")
    p:Slider(cfg, "chatInputX", "Edit box left / right", -30, 30, 1)
    p:Check(cfg, "chatEditColor", "Channel colour on the edit box", "The edit box edge takes the colour of the channel you are typing in (party, guild, whisper...), brighter while you type. Applies after a reload.")
    p:Check(cfg, "meter", "Damage meter", "Blizzard's built-in damage meter in a Tempus panel with flat bars. Applies after a reload.")
    p:Slider(cfg, "meterAlpha", "Damage meter opacity", 0, 1, 0.05, UI.pct)
    p:Section("Quest tracker")
    p:Check(cfg, "trackerPanel", "Panel behind the quest tracker", "A translucent Tempus panel sized to your tracked quests.")
    p:Slider(cfg, "trackerAlpha", "Panel opacity", 0.1, 1, 0.05, UI.pct)
    p:Section("Other addons")
    p:Check(cfg, "bagnon", "Bagnon", "Tempus skin for Bagnon's frames and square item slots with quality borders.")
    p:Check(cfg, "dbm", "DBM timers", "Adds a 'Tempus' skin to DBM's bar skins.")
    p:Newline()
    p:Add(W.Button("Use Tempus skin in DBM", function() T.Skins:ApplyDBM() end, "Switches DBM's timer bars to the Tempus skin now."))
    p:Add(W.Button("Reload UI", function() ReloadUI() end))
    p:Section("Diagnostics", "For building new skins. Records the structure of Blizzard's damage meter into saved data; reload afterwards so it is written to disk.")
    p:Add(W.Button("Record damage meter structure", function()
        local lines, frames = T:RunMeterProbe()
        T:Print("damage meter probe: %d lines from %d frames. Reload so it is saved to disk.", lines, frames)
    end))
end })
