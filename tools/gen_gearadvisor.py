#!/usr/bin/env python3
"""Gear Advisor data tools.

  weights   regenerate Modules/GearAdvisor/Weights.lua from tools/gearadvisor/pawn_forever_weights.lua
            and tools/gearadvisor/statmap.json (edit the map after reading real /tempus gearstats output)
  signals   regenerate Modules/GearAdvisor/TalentSignalsData.lua from tools/gearadvisor/signatures.txt
            (pasted /tempus gearsig lines labelled with a build)
  tabs      regenerate Modules/GearAdvisor/TalentTabsData.lua from pasted /tempus geartree files in
            tools/gearadvisor/trees/ and tools/gearadvisor/tabs.json
  stats     report on pasted /tempus gearstats output in tools/gearadvisor/stats-samples/*.txt

Add --check to weights or signals to verify the generated file is current. See docs/gear-advisor-data.md.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "tools" / "gearadvisor"
WEIGHTS_OUT = ROOT / "Modules" / "GearAdvisor" / "Weights.lua"
SIGNALS_OUT = ROOT / "Modules" / "GearAdvisor" / "TalentSignalsData.lua"
TABS_OUT = ROOT / "Modules" / "GearAdvisor" / "TalentTabsData.lua"

WEIGHTS_HEADER = """-- Stat weights per class and role, as data. GENERATED by tools/gen_gearadvisor.py weights: edit
-- tools/gearadvisor/statmap.json (or the source copy of the weights), not this file.
-- Source: GearQuest Forever (Henrik8210), as published in Pawn Forever (turlockmike, MIT). These are community
-- estimates, not measured from the game, so Gear Advisor labels every score built from them as an estimate.
-- Pawn counts crit, hit, haste, dodge, parry and block per 1%; they are divided by the rating per 1% Pawn
-- Forever measured on Forever tooltips (crit 14, hit 10, dodge 12, parry 15; haste 10 and block 5 are its
-- estimates) to give a weight per rating point. Stat names are the game's ITEM_MOD_* keys; the ones not yet
-- seen on a Forever item are assumed until /tempus gearstats confirms them (see statmap.json).
-- DPS_RANGED is the weight for a ranged weapon's DPS. Expertise, defense, health, mana and resistances are
-- left out: no verified conversion yet.
local _, T = ...
local GA = T.GearAdvisor or {}
T.GearAdvisor = GA
GA.Weights = {
    source = "GearQuest Forever via Pawn Forever (estimate)",
"""

DRUID_CODES = {"feral": "CAT", "bear": "BEAR", "restoration": "RESTO", "balance": "BALANCE"}
DRUID_LABELS = {"feral": "Cat", "bear": "Bear", "restoration": "Restoration", "balance": "Balance"}


def parse_table(text):
    out = {}
    for part in text.split(","):
        part = part.strip()
        if part:
            k, v = part.split("=")
            out[k.strip()] = float(v)
    return out


def read_pawn(path):
    text = path.read_text(encoding="utf-8")
    pattern = (r'\{ class = "(\w+)", classID = \d+, key = "(\w+)", specID = \w+, label = "([^"]+)",'
               r"\s*leveling = \{(.*?)\},\s*max = \{(.*?)\} \}")
    return [m.groups() for m in re.finditer(pattern, text, re.S)]


def convert(weights, smap):
    out = {}
    for stat, v in weights.items():
        if stat in smap["stats"]:
            for key in smap["stats"][stat]["keys"]:
                out[key] = v
        elif stat in smap["ratings"]:
            r = smap["ratings"][stat]
            for key in r["keys"]:
                out[key] = round(v / r["per"], 4)
    for key, source in smap["spell_power"]["keys"].items():
        value = max(weights.get("Healing", 0), weights.get("SpellDamage", 0)) if source == "max" else weights.get(source, 0)
        if value:
            out[key] = value
    return {k: v for k, v in out.items() if v > 0}


def fmt(d):
    return "{ " + ", ".join(f"{k} = {d[k]:g}" for k in sorted(d)) + " }"


def render_weights(pawn_path=None, map_path=None):
    smap = json.loads((map_path or DATA / "statmap.json").read_text(encoding="utf-8"))
    classes = {}
    for cls, key, label, lv, mx in read_pawn(pawn_path or DATA / "pawn_forever_weights.lua"):
        if cls == "DRUID":
            code, lab = DRUID_CODES[key], DRUID_LABELS[key]
        else:
            code, lab = key.upper(), label.replace(" Forever", "")
        classes.setdefault(cls, []).append((code, lab, convert(parse_table(lv), smap), convert(parse_table(mx), smap)))
    lines = [WEIGHTS_HEADER.rstrip("\n")]
    for cls, roles in classes.items():
        lines.append(f"    {cls} = {{")
        lines.append("        _order = { " + ", ".join(f'"{r[0]}"' for r in roles) + " },")
        for code, lab, lv, mx in roles:
            lines.append(f'        {code} = {{ label = "{lab}",')
            lines.append(f"            leveling = {fmt(lv)},")
            lines.append(f"            max = {fmt(mx)} }},")
        lines.append("    },")
    lines += ["}", ""]
    return "\n".join(lines)


SIG_LINE = re.compile(r"^\s*ROLE=(\w+)\s*\|\s*(\w+)\s+(\d+),\s*\d+\s+points:\s*(.*)$")


def parse_signatures(text):
    """ -> { class: { role: { talent: max rank } } } """
    out = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = SIG_LINE.match(line)
        if not m:
            raise SystemExit(f"cannot read signature line: {raw!r}")
        role, cls, _level, rest = m.groups()
        talents = {}
        if not rest.startswith("none"):
            for part in rest.split(","):
                part = part.strip()
                mm = re.match(r"^(.*) x(\d+)$", part)
                if not mm:
                    raise SystemExit(f"cannot read talent {part!r} in: {raw!r}")
                talents[mm.group(1).strip()] = int(mm.group(2))
        sample = out.setdefault(cls, {}).setdefault(role, {})
        for name, rank in talents.items():
            sample[name] = max(sample.get(name, 0), rank)
    return out


def markers(samples):
    """A talent marks a build when only that build's samples have points in it."""
    result = {}
    for cls, roles in samples.items():
        if len(roles) < 2:
            continue
        for role, talents in roles.items():
            others = set()
            for other, t in roles.items():
                if other != role:
                    others |= set(t)
            picks = sorted(name for name in talents if name not in others)
            if picks:
                result.setdefault(cls, {})[role] = picks
    return result


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_signals(path=None):
    samples = parse_signatures((path or DATA / "signatures.txt").read_text(encoding="utf-8"))
    marks = markers(samples)
    lines = ["-- Talent markers per build. GENERATED by tools/gen_gearadvisor.py signals from",
             "-- tools/gearadvisor/signatures.txt (pasted /tempus gearsig lines). Do not edit by hand.",
             "local _, T = ...", "local GA = T.GearAdvisor or {}", "T.GearAdvisor = GA",
             "GA.TalentSignals = GA.TalentSignals or {}"]
    for cls in sorted(marks):
        lines.append(f"GA.TalentSignals.{cls} = {{")
        for role in sorted(marks[cls]):
            sigs = ", ".join("{ %s, 1 }" % lua_str(n) for n in marks[cls][role])
            lines.append(f"    {role} = {{ {sigs} }},")
        lines.append("}")
    lines.append("")
    return "\n".join(lines)


def tree_positions(text):
    """ -> (class, [x of each talent]) from a pasted /tempus geartree """
    m = re.match(r"\s*(\w+) tree", text)
    if not m:
        raise SystemExit("cannot read the tree header")
    return m.group(1), [int(x) for x in re.findall(r"@(\d+),\d+", text)]


def tab_bounds(xs, gap=1500):
    """ upper x bound of each tab: talents in a tab sit close together, tabs are far apart """
    xs = sorted(set(xs))
    bounds = []
    for a, b in zip(xs, xs[1:]):
        if b - a > gap:
            bounds.append((a + b) // 2)
    return bounds


def render_tabs(tree_dir=None, tabs_path=None):
    roles = json.loads((tabs_path or DATA / "tabs.json").read_text(encoding="utf-8"))
    lines = ["-- The three talent tabs of each class, split by talent x position. GENERATED by",
             "-- tools/gen_gearadvisor.py tabs from tools/gearadvisor/trees/*.txt (pasted /tempus geartree) and",
             "-- tools/gearadvisor/tabs.json. Do not edit by hand.",
             "local _, T = ...", "local GA = T.GearAdvisor or {}", "T.GearAdvisor = GA", "GA.TalentTabs = GA.TalentTabs or {}"]
    for f in sorted((tree_dir or DATA / "trees").glob("*.txt")):
        cls, xs = tree_positions(f.read_text(encoding="utf-8"))
        names = roles.get(cls)
        bounds = tab_bounds(xs)
        if not names or len(bounds) != len(names) - 1:
            raise SystemExit(f"{f.name}: need {len(names or [])} tabs for {cls} in tabs.json, found {len(bounds) + 1} in the tree")
        entries = ", ".join('{ "%s", %d }' % (n, b) for n, b in zip(names, bounds + [1000000000]))
        lines.append(f"GA.TalentTabs.{cls} = {{ {entries} }}")
    lines.append("")
    return "\n".join(lines)


COLOR = re.compile(r"\|c[0-9a-fA-F]{8}|\|r")
STAT_LINE = re.compile(r"^(?:NO WEIGHT\s+)?(\S+): (\d+) items?, (.+?), e\.g\. (.*)$")


def parse_stats(text):
    """ -> { key: { items, range, example } } merged over lines """
    seen = {}
    for raw in text.splitlines():
        line = COLOR.sub("", raw).strip()
        line = re.sub(r"^Tempus:\s*", "", line)
        m = STAT_LINE.match(line)
        if m:
            key, n, rng, example = m.groups()
            e = seen.setdefault(key, {"items": 0, "range": rng, "example": example})
            e["items"] += int(n)
    return seen


def stats_report(sample_dir=None, map_path=None):
    smap = json.loads((map_path or DATA / "statmap.json").read_text(encoding="utf-8"))
    seen_keys = set(smap.get("seen", []))
    mapped = {}
    for name, v in {**smap["stats"], **smap["ratings"]}.items():
        for key in v["keys"]:
            mapped[key] = (name, "seen" if key in seen_keys else v["status"])
    for key, source in smap["spell_power"]["keys"].items():
        mapped[key] = (source if source != "max" else "Healing/SpellDamage", "seen" if key in seen_keys else smap["spell_power"]["status"])
    seen = {}
    files = sorted((sample_dir or DATA / "stats-samples").glob("*.txt"))
    for f in files:
        for key, e in parse_stats(f.read_text(encoding="utf-8")).items():
            cur = seen.setdefault(key, {"items": 0, "example": e["example"], "range": e["range"]})
            cur["items"] += e["items"]
    out = [f"{len(files)} sample file(s), {len(seen)} stat names seen", ""]
    out.append("Seen on real items:")
    for key in sorted(seen):
        if key in mapped:
            out.append(f"  {key:44} {seen[key]['items']:4} items  weight: {mapped[key][0]} ({mapped[key][1]})")
        else:
            out.append(f"  {key:44} {seen[key]['items']:4} items  NO WEIGHT  e.g. {seen[key]['example']}")
    out.append("")
    out.append("Mapped but not seen yet (still assumed):")
    for key in sorted(mapped):
        if key not in seen and mapped[key][1] not in ("internal",):
            out.append(f"  {key:44} {mapped[key][0]} ({mapped[key][1]})")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("what", choices=["weights", "signals", "tabs", "stats"])
    ap.add_argument("--check", action="store_true", help="verify the generated file is current")
    ap.add_argument("--output", type=Path, help="write here instead of the default file")
    ap.add_argument("--input", type=Path, help="signatures file, or stats samples folder")
    args = ap.parse_args(argv)
    if args.what == "stats":
        print(stats_report(args.input))
        return 0
    if args.what == "weights":
        text, target = render_weights(), args.output or WEIGHTS_OUT
    elif args.what == "tabs":
        text, target = render_tabs(args.input), args.output or TABS_OUT
    else:
        text, target = render_signals(args.input), args.output or SIGNALS_OUT
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"{target.name} is stale: run python3 tools/gen_gearadvisor.py {args.what}", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
